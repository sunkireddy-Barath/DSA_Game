export type Diff = 'E' | 'M' | 'H';
export interface SheetProblem { id: string; title: string; diff: Diff; step: number; topic: number }
export interface SheetTopic { name: string; diff: Diff; problems: SheetProblem[] }
export interface SheetStep { n: number; name: string; topics: SheetTopic[] }

export function parseSheet(raw: string): SheetStep[] {
  const steps: SheetStep[] = [];
  let step: SheetStep | null = null, topic: SheetTopic | null = null;
  for (const line of raw.split('\n').map(l => l.trim()).filter(Boolean)) {
    if (line.startsWith('# ')) {
      const m = line.slice(2).match(/^Step (\d+):\s*(.*)$/)!;
      step = { n: +m[1], name: m[2], topics: [] }; steps.push(step);
    } else if (line.startsWith('## ')) {
      const m = line.slice(3).match(/^(.*) \[([EMH])\]$/)!;
      topic = { name: m[1], diff: m[2] as Diff, problems: [] }; step!.topics.push(topic);
    } else {
      const ti = step!.topics.length - 1;
      topic!.problems.push({ id: `s${step!.n}.${ti}.${topic!.problems.length}`, title: line, diff: topic!.diff, step: step!.n, topic: ti });
    }
  }
  return steps;
}

export const SHEET = parseSheet(RAW);
export const ALL_PROBLEMS: SheetProblem[] = SHEET.flatMap(s => s.topics.flatMap(t => t.problems));
export const PROBLEM_BY_ID = new Map(ALL_PROBLEMS.map(p => [p.id, p]));
